// Exercise real React loading/error branches using explicit local-only request interception.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const base=process.env.A5_PREVIEW_URL || 'http://127.0.0.1:3105'
function gate(){let release;const promise=new Promise(resolve=>release=resolve);return{promise,release}}
;(async()=>{
  assert.ok(['127.0.0.1','localhost'].includes(new URL(base).hostname))
  fs.mkdirSync('.local',{recursive:true})
  const browser=await chromium.launch({channel:'chrome',headless:true})
  const page=await browser.newPage({viewport:{width:1440,height:900}}), errors=[],passed=[]
  page.on('pageerror',e=>errors.push(e.message))
  async function capture(state){
    await page.evaluate(()=>document.fonts.ready)
    for(const width of [375,1440]){
      await page.setViewportSize({width,height:width===375?667:900})
      if(state==='profile-reading')await page.getByRole('heading',{name:'正在了解你的兴趣。'}).waitFor()
      await page.evaluate(()=>window.scrollTo(0,0))
      await page.screenshot({path:`.local/v25-process-${state}-${width}.png`,fullPage:true})
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    }
    passed.push(state)
  }
  const identity=gate(),profile=gate()
  await page.route('**/api/auth/development',async r=>{await identity.promise;await r.continue()},{times:1})
  await page.route('**/api/adoption/profile',async r=>{await profile.promise;await r.continue()},{times:1})
  await page.goto(base+'/adopt')
  await page.getByRole('button',{name:'以测试身份开始 →'}).click()
  await page.getByText('等待身份确认',{exact:true}).waitFor()
  await capture('identity-waiting')
  identity.release()
  await page.getByRole('heading',{name:'正在了解你的兴趣。'}).waitFor()
  await capture('profile-reading')
  profile.release()
  await page.getByRole('button',{name:'继续，给它起个名字 →'}).click()
  await page.locator('#dog-name').fill('小山')
  await page.getByRole('button',{name:'继续，认识它的性格 →'}).click()
  await page.route('**/api/adoption/personality',r=>r.fulfill({status:503,json:{publicMessage:'本次测试：性格生成服务暂时不可用'}}),{times:1})
  await page.getByRole('button',{name:'看看它的三个词 →'}).click()
  await page.getByText('生成暂时失败',{exact:true}).waitFor()
  await capture('generation-failure')
  const generation=gate()
  await page.route('**/api/adoption/personality',async r=>{await generation.promise;await r.continue()},{times:1})
  await page.getByRole('button',{name:'再试一次 →',exact:true}).click()
  await page.getByText('正在整理它的初始性格',{exact:true}).waitFor()
  await capture('generation-loading')
  generation.release()
  await page.getByRole('button',{name:'去挑一套穿搭 →'}).click()
  await page.route('**/api/dogs',r=>r.fulfill({status:503,json:{publicMessage:'本次测试：创建服务暂时不可用'}}),{times:1})
  await page.getByRole('button',{name:'就这样，成为伙伴 →'}).click()
  await page.getByText('创建暂时失败',{exact:true}).waitFor()
  await capture('creation-failure')
  const creation=gate()
  await page.route('**/api/dogs',async r=>{await creation.promise;await r.continue()},{times:1})
  await page.getByRole('button',{name:'保留选择，再试一次 →'}).click()
  await page.getByText('正在创建',{exact:true}).waitFor()
  await capture('creation-loading')
  creation.release()
  await page.getByRole('button',{name:'进入它的小屋 →'}).waitFor()
  await capture('creation-success')
  // A separate identity checks total profile failure and distinguishes empty from partial.
  const other=await browser.newPage({viewport:{width:1440,height:900}})
  other.on('pageerror',e=>errors.push(e.message))
  await other.route('**/api/adoption/profile',r=>r.fulfill({status:503,json:{publicMessage:'本次测试：资料读取失败'}}),{times:1})
  await other.goto(base+'/adopt')
  await other.getByRole('button',{name:'以测试身份开始 →'}).click()
  await other.getByText('本次测试：资料读取失败',{exact:true}).waitFor()
  assert.equal(await other.getByRole('button',{name:'继续，给它起个名字 →'}).count(),0)
  await other.screenshot({path:'.local/v25-process-profile-failure-1440.png',fullPage:true})
  passed.push('profile-failure-blocks-continue')
  await other.route('**/api/adoption/profile',r=>r.fulfill({json:{source:'mock',version:'empty-review',sections:{basic:{status:'ok'},collections:{status:'empty'},followees:{status:'empty'},contents:{status:'empty'}}}}),{times:1})
  await other.getByRole('button',{name:'重新读取 →'}).click()
  await other.getByText('没有内容 ≠ 读取失败',{exact:true}).waitFor()
  await other.getByRole('button',{name:'继续，给它起个名字 →'}).waitFor()
  passed.push('profile-empty-can-continue')
  assert.deepEqual(errors,[])
  fs.writeFileSync('.local/v25-process-result.json',JSON.stringify({passed,errors},null,2))
  await browser.close()
  console.log(`PASS ${passed.length} process states; screenshots .local/v25-process-*`)
})().catch(e=>{console.error(e);process.exit(1)})
