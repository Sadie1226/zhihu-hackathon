// Preserve the checked-in A4 cascade verbatim, with a product-local theme scope.
// Source snapshots stay immutable; only paths and selector scoping are transformed.
const fs = require('node:fs')
const path = require('node:path')
const postcss = require('postcss')
const root = path.resolve('app/(a)/_design/a4-v25')
let output = '/* Generated by scripts/a5/sync-v25.cjs. Edit the scoped overrides, not the A4 snapshot. */\n'
output += '[data-v25]{min-height:100dvh}[data-v25] main{max-width:none;margin:0;padding:0;line-height:inherit}\n'
for (const name of ['styles.css','round2.css','home.css']) {
 const css = postcss.parse(fs.readFileSync(path.join(root,name),'utf8'))
 css.walkRules(rule => {
  rule.selectors = rule.selectors.map(selector => {
   if(selector === ':root' || selector === 'body') return '[data-v25]'
   if(selector.startsWith('.home-page ')) return '[data-v25].home-page ' + selector.slice(11)
   return '[data-v25] ' + selector
  })
 })
 css.walkDecls(decl => { decl.value=decl.value.replaceAll("url('assets/", "url('/assets/a5-v25/") })
 output += `\n/* Source: ${name} */\n` + css.toString() + '\n'
}
fs.writeFileSync('components/v25/theme.css',output.trimEnd()+'\n')
for(const name of ['AI素材组合.png','welcome.png','head-cancel.png','head-failure.png',...Array.from({length:6},(_,i)=>`interest-${i}.png`)])
 fs.copyFileSync(path.join(root,'assets',name),path.join('public/assets/a5-v25',name))
console.log('Scoped v25 cascade and 10 missing live assets synchronized.')
